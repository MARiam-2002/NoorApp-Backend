export const STANCE_SITUATION_COUNT = STANCE_SITUATIONS.length;

export function getStanceById(id: string): StanceSituation | undefined {
  return STANCE_SITUATIONS.find((x) => x.id === id);
}

export function getStanceBySortOrder(sortOrder: number): StanceSituation | undefined {
  return STANCE_SITUATIONS.find((x) => x.sortOrder === sortOrder);
}

/** 1..366 dayOfYear → stable situation for "موقف اليوم". */
export function getStanceForDayOfYear(dayOfYear: number): StanceSituation {
  const idx = ((Math.max(1, Math.floor(dayOfYear)) - 1) % STANCE_SITUATION_COUNT + STANCE_SITUATION_COUNT) %
    STANCE_SITUATION_COUNT;
  return STANCE_SITUATIONS[idx]!;
}

export function getNextStance(afterId: string): StanceSituation {
  const current = getStanceById(afterId);
  if (!current) return STANCE_SITUATIONS[0]!;
  const nextOrder = current.sortOrder >= STANCE_SITUATION_COUNT ? 1 : current.sortOrder + 1;
  return getStanceBySortOrder(nextOrder) ?? STANCE_SITUATIONS[0]!;
}

export function getPrevStance(beforeId: string): StanceSituation {
  const current = getStanceById(beforeId);
  if (!current) return STANCE_SITUATIONS[0]!;
  const prevOrder = current.sortOrder <= 1 ? STANCE_SITUATION_COUNT : current.sortOrder - 1;
  return getStanceBySortOrder(prevOrder) ?? STANCE_SITUATIONS[0]!;
}
