/**
 * Builds src/shared/data/learning-tafsir.ts: «التفسير الميسر» (King Fahd Glorious Quran Printing Complex, revised
 * edition) for every Quran block in «تعلّم مع نور». The listening script reads it after the reciter recites the ayat,
 * and the reader shows it under the ayat, so stories are told by published tafsir instead of Noor's own wording.
 *
 * Source text: prisma/data/tafsir/ar-muyassar.json — quran.com's tafsir data as published in spa5k/tafsir_api
 * (commit eb82bb6), pinned by SHA-256. Every passage that is used must equal, letter for letter and with the same ayah
 * grouping, an independent copy: prisma/data/tafsir/muyassar-tafsir-app-full.json.gz (الباحث القرآني, tafsir.app).
 * Surah introductions («تسمية السورة / مقاصد السورة») are not part of the ayah tafsir and are dropped.
 *
 *   npx tsx scripts/build-learning-tafsir.ts          # rebuild
 *   npx tsx scripts/build-learning-tafsir.ts --check  # fail if the committed file is out of date
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gunzipSync } from 'node:zlib';
import { LEARNING_COLLECTIONS_DATA } from '../src/shared/data/learning-content';
import { EDITOR_NOTES, lettersKey, tafsirBody } from './lib/muyassar';

const DIR = join(process.cwd(), 'prisma', 'data', 'tafsir');
const OUT = join(process.cwd(), 'src', 'shared', 'data', 'learning-tafsir.ts');
const PINNED: Record<string, string> = {
  'ar-muyassar.json': '6498c662415947fcb4ce028ddfc741c8f226d16f363e95f911a0d325e8c39241',
  'muyassar-tafsir-app-full.json.gz': '4ffba10bd08a7a8950272a24fd08adfc5ac9767c8e99daaa42ccff8be6dadbb2',
};
for (const [f, sha] of Object.entries(PINNED)) {
  const got = createHash('sha256').update(readFileSync(join(DIR, f))).digest('hex');
  if (got !== sha) throw new Error(`${f} changed (sha256 ${got}); review it and update PINNED`);
}
const source = JSON.parse(readFileSync(join(DIR, 'ar-muyassar.json'), 'utf8')) as Record<string, string>;
const cross = (JSON.parse(gunzipSync(readFileSync(join(DIR, 'muyassar-tafsir-app-full.json.gz'))).toString('utf8')) as {
  entries: Record<string, { start: number; count: number; text: string }>;
}).entries;

type Passage = { surah: number; fromAyah: number; toAyah: number; textAr: string };
const passages = new Map<string, Passage>();
const byBlock: Record<string, string[]> = {};
const at = (s: number, a: number) => source[`${s}:${a}`];

for (const c of LEARNING_COLLECTIONS_DATA) for (const item of c.items) for (const sec of item.sections) for (const q of sec.quran) {
  const blockKey = `${q.surah}:${q.fromAyah}-${q.toAyah}`;
  const keys: string[] = [];
  let a = q.fromAyah;
  while (a <= q.toAyah) {
    const raw = at(q.surah, a);
    if (!raw) throw new Error(`No tafsir for ${q.surah}:${a}`);
    // An ayah group shares one passage: the same text repeated on each of its ayat.
    let from = a; while (at(q.surah, from - 1) === raw) from--;
    let to = a; while (at(q.surah, to + 1) === raw) to++;
    const key = `${q.surah}:${from}-${to}`;
    if (!passages.has(key)) {
      const textAr = tafsirBody(raw);
      const check = cross[`${q.surah}:${from}`];
      if (!check) throw new Error(`${key}: no tafsir.app entry for ${q.surah}:${from}`);
      if (check.start !== from || check.start + check.count - 1 !== to) throw new Error(`${key}: ayah grouping differs from tafsir.app (${check.start}+${check.count})`);
      if (lettersKey(textAr) !== lettersKey(tafsirBody(check.text))) throw new Error(`${key}: text differs from tafsir.app`);
      if (EDITOR_NOTES.test(textAr)) throw new Error(`${key}: editor note or introduction left in the text`);
      if (textAr.length < 20) throw new Error(`${key}: suspiciously short`);
      passages.set(key, { surah: q.surah, fromAyah: from, toAyah: to, textAr });
    }
    if (!keys.includes(key)) keys.push(key);
    a = to + 1;
  }
  byBlock[blockKey] = keys;
}

const sorted = [...passages.entries()].sort(([, x], [, y]) => x.surah - y.surah || x.fromAyah - y.fromAyah);
const header = `/**
 * Generated by scripts/build-learning-tafsir.ts — do not edit by hand.
 * «التفسير الميسر» (revised edition) for the Quran blocks of «تعلّم مع نور». Each passage is checked letter for letter and
 * by ayah grouping against an independent copy (tafsir.app). Source files pinned by SHA-256 in the build script.
 */
`;
const body = `export const LEARNING_TAFSIR_SOURCE = {
  id: 'muyassar',
  titleAr: 'التفسير الميسر',
  authorAr: 'نخبة من العلماء بإشراف مجمع الملك فهد لطباعة المصحف الشريف',
  sourceAr: 'التفسير الميسر — مجمع الملك فهد لطباعة المصحف الشريف',
  noteAr: 'نص الطبعة المنقحة كما هو، مطابق حرفيًا لنسخة «الباحث القرآني».',
} as const;

export type LearningTafsirPassage = { surah: number; fromAyah: number; toAyah: number; textAr: string };

/** Key: "surah:fromAyah-toAyah" of the tafsir's own ayah group. */
export const LEARNING_TAFSIR_PASSAGES: Record<string, LearningTafsirPassage> = ${JSON.stringify(Object.fromEntries(sorted), null, 1)};

/** Key: a learning Quran block "surah:fromAyah-toAyah" → the passages that explain it, in order. */
export const LEARNING_TAFSIR_BY_BLOCK: Record<string, string[]> = ${JSON.stringify(byBlock, null, 1)};
`;
const content = header + body;
if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== content) { console.error('src/shared/data/learning-tafsir.ts is out of date: run npx tsx scripts/build-learning-tafsir.ts'); process.exit(1); }
  console.log('learning tafsir up to date');
} else {
  writeFileSync(OUT, content);
  console.log(`learning tafsir: ${sorted.length} passages for ${Object.keys(byBlock).length} Quran blocks, ${Math.round(content.length / 1024)} KB`);
}
