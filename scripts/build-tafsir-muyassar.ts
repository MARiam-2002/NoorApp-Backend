/**
 * Builds the verified «التفسير الميسر» served by GET /quran/tafsir for tafsirId Ibn_Kathir_Muyassar (resource 16):
 * src/shared/data/tafsir-muyassar/muyassar.json.gz (+ src/shared/data/tafsir-muyassar.ts with its checksum).
 *
 * Why: Quran Foundation's live resource 16 mixes the first and revised editions ayah by ayah, has typing errors
 * (8:39 «قتنة», 6:99 «أخرح», 7:85 «الكيل، الميزان»…) and a digitiser's note in 27:25. Here every ayah group of the whole
 * Quran must equal, letter for letter and with the same ayah grouping, an independent copy (tafsir.app). Surah
 * introductions are not ayah tafsir and are dropped.
 *
 *   npx tsx scripts/build-tafsir-muyassar.ts          # rebuild
 *   npx tsx scripts/build-tafsir-muyassar.ts --check  # fail if the committed files are out of date
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gunzipSync, gzipSync } from 'node:zlib';
import { CATALOG_SURAHS } from '../src/data/surahs';
import { EDITOR_NOTES, lettersKey, tafsirBody } from './lib/muyassar';

const DIR = join(process.cwd(), 'prisma', 'data', 'tafsir');
const OUT_DIR = join(process.cwd(), 'src', 'shared', 'data', 'tafsir-muyassar');
const OUT_GZ = join(OUT_DIR, 'muyassar.json.gz');
const OUT_TS = join(process.cwd(), 'src', 'shared', 'data', 'tafsir-muyassar.ts');
const PINNED: Record<string, string> = {
  'ar-muyassar.json': '6498c662415947fcb4ce028ddfc741c8f226d16f363e95f911a0d325e8c39241',
  'muyassar-tafsir-app-full.json.gz': '4ffba10bd08a7a8950272a24fd08adfc5ac9767c8e99daaa42ccff8be6dadbb2',
};
const sha = (b: Buffer | string) => createHash('sha256').update(b).digest('hex');
for (const [f, want] of Object.entries(PINNED)) {
  const got = sha(readFileSync(join(DIR, f)));
  if (got !== want) throw new Error(`${f} changed (sha256 ${got}); review it and update PINNED`);
}
const source = JSON.parse(readFileSync(join(DIR, 'ar-muyassar.json'), 'utf8')) as Record<string, string>;
const cross = JSON.parse(gunzipSync(readFileSync(join(DIR, 'muyassar-tafsir-app-full.json.gz'))).toString('utf8')) as {
  entries: Record<string, { start: number; count: number; text: string }>;
};

const rows: [number, number, number, string][] = [];
const problems: string[] = [];
for (const s of CATALOG_SURAHS) {
  let a = 1;
  while (a <= s.totalAyahs) {
    const raw = source[`${s.id}:${a}`];
    if (!raw) throw new Error(`No tafsir for ${s.id}:${a}`);
    let to = a; while (source[`${s.id}:${to + 1}`] === raw) to++;
    const text = tafsirBody(raw);
    const c = cross.entries[`${s.id}:${a}`];
    if (!c) problems.push(`${s.id}:${a}-${to} missing in tafsir.app copy`);
    else if (c.start !== a || c.start + c.count - 1 !== to) problems.push(`${s.id}:${a}-${to} grouping differs from tafsir.app (${c.start}+${c.count})`);
    else if (lettersKey(text) !== lettersKey(tafsirBody(c.text))) problems.push(`${s.id}:${a}-${to} text differs from tafsir.app`);
    if (EDITOR_NOTES.test(text)) problems.push(`${s.id}:${a}-${to} editor note or introduction left in the text`);
    rows.push([s.id, a, to, text]);
    a = to + 1;
  }
}
if (problems.length) { console.error(problems.join('\n')); throw new Error(`${problems.length} passages failed verification`); }

const ayat = rows.reduce((n, r) => n + r[2] - r[1] + 1, 0);
if (ayat !== 6236) throw new Error(`Covers ${ayat} ayat, expected 6236`);
const json = JSON.stringify(rows);
const gz = gzipSync(Buffer.from(json, 'utf8'), { level: 9 });
const ts = `/**
 * Generated by scripts/build-tafsir-muyassar.ts — do not edit by hand.
 * «التفسير الميسر» (revised edition), every ayah group of the Quran verified letter for letter and by grouping against
 * tafsir.app. Rows in tafsir-muyassar/muyassar.json.gz: [surah, fromAyah, toAyah, textAr];
 * jsonSha256 is the checksum of the decompressed JSON (checked when the server loads it).
 */
export const TAFSIR_MUYASSAR_FILE = { file: 'muyassar.json.gz', jsonSha256: '${sha(json)}', passages: ${rows.length}, ayat: ${ayat} } as const;
`;
if (process.argv.includes('--check')) {
  const okGz = sha(gunzipSync(readFileSync(OUT_GZ))) === sha(json);
  if (!okGz || readFileSync(OUT_TS, 'utf8') !== ts) { console.error('Muyassar data is out of date: run npx tsx scripts/build-tafsir-muyassar.ts'); process.exit(1); }
  console.log(`tafsir muyassar up to date (${rows.length} passages, ${ayat} ayat verified)`);
} else {
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT_GZ, gz);
  writeFileSync(OUT_TS, ts);
  console.log(`tafsir muyassar: ${rows.length} passages, ${ayat} ayat, ${Math.round(gz.length / 1024)} KB gz`);
}
