function minutes(hhmm: string): number {
  const [h, m] = hhmm.split(':').map(Number);
  return (h as number) * 60 + (m as number);
}

/** Ministries round to the minute differently; Asr and Moroccan sunrise/sunset also vary with city elevation. */
function tolerance(table: Table, key: (typeof KEYS)[number]): number {
  if (key === 'asr') return 2;
  if (table.tz === 'Africa/Casablanca' && (key === 'sunrise' || key === 'maghrib')) return 2;
  return 1;
}

let checked = 0;
for (const table of TABLES) {
  const worst: Record<string, number> = {};
  for (const row of table.rows) {
    const [date, ...official] = row.split(' ') as [string, ...string[]];
    const s = calculateDailyPrayerSchedule(table.lat, table.lng, table.tz, [], new Date(`${date}T12:00:00Z`), {
      method: 'AUTO',
      locationSource: 'profile',
    });
    assert.equal(s.calculationMethod, EXPECTED_METHOD[table.tz], table.city);
    const got: Record<string, string> = {
      ...Object.fromEntries(s.schedule.map((r) => [r.key.toLowerCase(), r.time])),
      sunrise: s.sunrise.time,
    };
    KEYS.forEach((key, i) => {
      const want = official[i]!;
      if (want === '--:--') return;
      const diff = minutes(got[key]!) - minutes(want);
      assert.ok(
        Math.abs(diff) <= tolerance(table, key),
        `${table.city} ${date} ${key}: app ${got[key]} vs official ${want}`,
      );
      worst[key] = Math.max(worst[key] ?? 0, Math.abs(diff));
      checked += 1;
    });
  }
  console.log(`${table.city.padEnd(14)} ${String(table.rows.length).padStart(2)} days, max diff (min) ${JSON.stringify(worst)}`);
}

// Morocco is back on GMT since 2026-09-20: times must not be shown one hour late.
const rabat = calculateDailyPrayerSchedule(34.0209, -6.8416, 'Africa/Casablanca', [], new Date('2026-10-01T12:00:00Z'), {
  method: 'AUTO',
  locationSource: 'profile',
});
const rabatFajr = rabat.schedule.find((r) => r.key === 'FAJR')!;
assert.ok(Math.abs(minutes(rabatFajr.time) - minutes('04:53')) <= 1, `Rabat Fajr ${rabatFajr.time}`);
assert.equal(rabatFajr.time, rabatFajr.iso.slice(11, 16), 'Rabat local time = UTC');

console.log(`official prayer tables: OK (${checked} times checked)`);
